toBinary <- function(decimal) {
  if (decimal == 0) {
    return('0')
  }
  binary <- ''
  while (decimal > 0) {
    binary <- paste0(decimal %% 2, binary)
    decimal <- decimal %/% 2
  }
  return(binary)
}

