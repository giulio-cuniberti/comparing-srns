## Conditions of Theorem 4.1 for stochastic reaction networks with monotone kinetics,
## evaluated in exact arithmetic.
##
## The conservation laws are an exact integer basis of the orthogonal complement
## of the stoichiometric subspace, obtained by the Gauss-Jordan method of
## Sauro and Ingalls, Biophys. Chem. 109 (2004) 1-15, Section 4.2; the feasibility
## questions are decided by cddlib in rational arithmetic.  No tolerance enters at
## any point, so the entries of A and B are exact.

## libraries #######################################################################################

library(rcdd)     # exact rational arithmetic (needs the GNU MP system library)
library(gmp)      # exact integer arithmetic, for conservation laws and M xi_r



## auxiliary functions #############################################################################

populateAB <- function (conservation.laws, preorder.matrix, rows = NULL) {
  checkIntegerInput(conservation.laws, "conservation.laws", allow.boundary = TRUE)
  checkIntegerInput(preorder.matrix, "preorder.matrix")
  m <- nrow(preorder.matrix)  # number of inequalities
  d <- ncol(preorder.matrix)  # number of species
  if (ncol(conservation.laws) != d) {
    stop('number of columns of matrices "conservation.laws" and "preorder.matrix" does not match')
  }
  A <- matrix(rep(0, (m+1)*d), nrow = m+1, ncol = d)
  B <- matrix(rep(0, (m+1)*d), nrow = m+1, ncol = d)
  N <- rbind(preorder.matrix, rep(0, d))  # preorder.matrix with extra 0 row
  # rows that checkConditions() can consult; the caller knows them from the
  # reaction vectors, and every other row of A and B is never read
  if (is.null(rows)) rows <- 1:(m+1)
  rows <- sort(union(rows, m+1), decreasing = TRUE)   # row m+1 first
  for (i in rows) {
    # the whole i-th row of A and of B comes from ONE description of the cone
    # generated by the columns of D: see coneRow() below
    D <- cbind(t(conservation.laws), -t(conservation.laws), t(preorder.matrix), -N[i, ])
    r <- coneRow(D, d)
    A[i, ] <- r$a
    B[i, ] <- r$b
  }
  return(list(A = A, B = B))
}

# ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

checkConditions <- function(source.complexes, reaction.vectors, conservation.laws, 
                            preorder.matrix) {
  checkIntegerInput(source.complexes, "source.complexes", nonnegative = TRUE)
  checkIntegerInput(reaction.vectors, "reaction.vectors")
  n <- nrow(source.complexes)  # number of reactions
  d <- ncol(source.complexes)  # number of species
  m <- nrow(preorder.matrix)  # number of inequalities
  if (nrow(reaction.vectors) != n) {
    stop('number of rows of matrices "source.complexes" and "reaction.vectors" does not match')
  }
  if ((ncol(reaction.vectors) != d) || (ncol(conservation.laws) != d) || 
      (ncol(preorder.matrix) != d)) {
    stop('number of columns of matrices "source.complexes", "reaction.vectors", "conservation.laws" 
          and "preorder.matrix" does not match')
  }
  # M xi_r for every reaction at once, exactly: column r of V is M xi_r
  V <- exactProduct(preorder.matrix, reaction.vectors)
  # compute matrices A and B, only the rows that can be consulted below
  AandB <- populateAB(conservation.laws, preorder.matrix, rows = neededRows(V))
  A <- AandB$A
  B <- AandB$B
  # create the output variables
  result <- 1
  ratesIneq <- matrix(rep(0, 2*n), nrow = 2)
  speciesIneq <- rbind(A[m+1, ], -B[m+1, ])
  firstFail <- ''
  # check conditions for each reaction
  for (r in 1:n) {
    vec <- V[, r]
    pos <- vec*(vec>0)
    neg <- -vec*(vec<0)
    check <- 0
    # conditions (a)
    if (all(pos == 0)) {
      check <- 1
    } else if (all(A[m+1, ]*source.complexes[r, ] == source.complexes[r, ])) {
      check <- 1
      ratesIneq[1, r] <- 1
    } else {
      for (i in 1:m) {
        e <- rep(0, m)
        e[i] <- 1
        if (all(pos == e) && all(A[i, ]*source.complexes[r, ] == source.complexes[r, ])) {
          check <- 1
          ratesIneq[1, r] <- 1
        }
      }
    }
    if (check != 1) {
      result <- 0
      firstFail <- paste('reaction', r, '/ conditions (a)')
      break
    }
    # conditions (b)
    if (all(neg == 0)) {
      check <- 2
    } else if (all(B[m+1, ]*source.complexes[r, ] == source.complexes[r, ])) {
      check <- 2
      ratesIneq[2, r] <- -1
    } else {
      for (i in 1:m) {
        e <- rep(0, m)
        e[i] <- 1
        if (all(neg == e) && all(B[i, ]*source.complexes[r, ] == source.complexes[r, ])) {
          check <- 2
          ratesIneq[2, r] <- -1
        }
      }
    }
    if (check != 2) {
      result <- 0
      firstFail <- paste('reaction', r, '/ conditions (b)')
      break
    }
  }
  return(list(result = result, rate.inequalities = ratesIneq, 
              species.inequalities = speciesIneq, first.fail = firstFail))
}

# ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

populateRC <- function(source.complexes, product.complexes) {
  checkIntegerInput(source.complexes, "source.complexes", nonnegative = TRUE)
  checkIntegerInput(product.complexes, "product.complexes", nonnegative = TRUE)
  storage.mode(source.complexes) <- "double"
  storage.mode(product.complexes) <- "double"
  n <- nrow(source.complexes)  # number of reactions
  d <- ncol(source.complexes)  # number of species
  if (nrow(product.complexes) != n) {
    stop('number of rows of matrices "source.complexes" and "product.complexes" does not match')
  }
  if ((ncol(product.complexes) != d)) {
    stop('number of columns of matrices "source.complexes" and "product.complexes" does not match')
  }
  reaction.vectors <- product.complexes-source.complexes         # matrix of reaction vectors
  # exact integer basis of S^perp, so that the matrix D of Theorem 4.1 has
  # integer entries
  K <- intKernelSI(reaction.vectors)
  conservation.laws <- if (nrow(K) == 0) matrix(rep(0, d), nrow = 1) else K
  return(list(R = reaction.vectors, C = conservation.laws))
}

